"""Convert a textured GLB into a small mesh header for the ESP32 rasterizer.

  python tools/convert_model.py model.glb --faces 4000

Decimates the mesh, bakes the base-colour texture into one RGB565 colour per face,
computes smooth vertex normals and writes gsx_3d_viewer/model.h. Big arrays are emitted
as string literals because GCC compiles those far faster than {0x..} initialisers.
"""
import argparse
import os

import fast_simplification
import numpy as np
import trimesh
from scipy.spatial import cKDTree

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "model.h")


def load(path):
    scene = trimesh.load(path)
    geoms = list(scene.geometry.values()) if isinstance(scene, trimesh.Scene) else [scene]
    g = geoms[0] if len(geoms) == 1 else None
    if g is None:
        raise SystemExit("expected a single textured mesh")
    mesh = scene.to_geometry() if isinstance(scene, trimesh.Scene) else scene
    tex = np.asarray(g.visual.material.baseColorTexture.convert("RGB"), dtype=np.float32)
    return mesh.vertices.astype(np.float64), mesh.faces, g.visual.uv, tex


def sample_tex(tex, uv):
    h, w, _ = tex.shape
    x = np.clip((uv[:, 0] % 1.0) * (w - 1), 0, w - 1).astype(int)
    y = np.clip((1.0 - uv[:, 1] % 1.0) * (h - 1), 0, h - 1).astype(int)
    # small box filter so a sample doesn't land on a single noisy texel
    acc = np.zeros((len(uv), 3), np.float32)
    for dx in (-2, 0, 2):
        for dy in (-2, 0, 2):
            acc += tex[np.clip(y + dy, 0, h - 1), np.clip(x + dx, 0, w - 1)]
    return acc / 9


def face_colors(v0, f0, uv0, tex, v1, f1):
    """Colour each decimated face from the nearest faces of the original textured mesh."""
    cent0 = v0[f0].mean(axis=1)
    uvc0 = uv0[f0].mean(axis=1)
    tree = cKDTree(cent0)
    tri = v1[f1]
    c = tri.mean(axis=1)
    pts = [c] + [(c + tri[:, i]) * 0.5 for i in range(3)]
    col = np.zeros((len(f1), 3), np.float32)
    for p in pts:
        _, idx = tree.query(p)
        col += sample_tex(tex, uvc0[idx])
    return col / len(pts)


def vertex_normals(v, f):
    fn = np.cross(v[f[:, 1]] - v[f[:, 0]], v[f[:, 2]] - v[f[:, 0]])
    vn = np.zeros_like(v)
    for i in range(3):
        np.add.at(vn, f[:, i], fn)
    vn /= np.linalg.norm(vn, axis=1, keepdims=True) + 1e-12
    return vn


def c_str(data: bytes):
    lines, line = [], ""
    for b in data:
        line += "\\x%02x" % b
        if len(line) >= 120:
            lines.append('  "%s"' % line)
            line = ""
    if line:
        lines.append('  "%s"' % line)
    return "\n".join(lines)


def arr(name, ctype, data):
    # alignas(4) byte array from a string literal, then a typed alias (Xtensa needs aligned loads)
    return ("alignas(4) static const uint8_t %s_BYTES[%d] =\n%s;\n#define %s ((const %s *)%s_BYTES)\n\n"
            %(name, len(data) + 1, c_str(data), name, ctype, name))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("glb")
    ap.add_argument("--faces", type=int, default=4000)
    ap.add_argument("--npz", help="also save the decimated mesh here (for the preview renderer)")
    a = ap.parse_args()

    v0, f0, uv0, tex = load(a.glb)
    print("source:", len(v0), "verts", len(f0), "faces, texture", tex.shape)

    v1, f1 = fast_simplification.simplify(v0.astype(np.float32), f0.astype(np.int32),
                                          target_count=a.faces)
    v1 = v1.astype(np.float64)
    # drop degenerate faces left by the collapse
    area = np.linalg.norm(np.cross(v1[f1[:, 1]] - v1[f1[:, 0]], v1[f1[:, 2]] - v1[f1[:, 0]]), axis=1)
    f1 = f1[area > 1e-10]
    print("decimated:", len(v1), "verts", len(f1), "faces")

    col = face_colors(v0, f0, uv0, tex, v1, f1)
    vn = vertex_normals(v1, f1)

    # centre and scale so the longest half-extent maps to 32767
    lo, hi = v1.min(0), v1.max(0)
    v1 = v1 - (lo + hi) / 2
    scale = 32767 / np.abs(v1).max()
    vq = np.round(v1 * scale).astype("<i2")
    nq = np.round(vn * 127).astype("i1")
    r, g, b = [np.clip(col[:, i], 0, 255).astype(np.uint16) for i in range(3)]
    c565 = ((r & 0xF8) << 8 | (g & 0xFC) << 3 | b >> 3).astype("<u2")
    fq = f1.astype("<u2")
    assert len(v1) < 65536

    if a.npz:
        np.savez(a.npz, v=vq, n=nq, f=fq, c=col.astype(np.uint8))

    with open(OUT, "w") as fh:
        fh.write("// Generated by tools/convert_model.py - Suzuki GSX-250R (Higgsfield / Tripo image-to-3D)\n")
        fh.write("#pragma once\n#include <stdint.h>\n\n")
        fh.write("#define MODEL_NV %d\n#define MODEL_NF %d\n\n" % (len(vq), len(fq)))
        fh.write("// int16 x,y,z per vertex, centred, longest half-extent = 32767\n")
        fh.write(arr("MODEL_V", "int16_t", vq.tobytes()))
        fh.write("// int8 x,y,z unit normal (x127) per vertex\n")
        fh.write(arr("MODEL_N", "int8_t", nq.tobytes()))
        fh.write("// uint16 vertex indices, 3 per face\n")
        fh.write(arr("MODEL_F", "uint16_t", fq.tobytes()))
        fh.write("// RGB565 base colour per face\n")
        fh.write(arr("MODEL_C", "uint16_t", c565.tobytes()))
    print("wrote", os.path.normpath(OUT), os.path.getsize(OUT) // 1024, "KB")


if __name__ == "__main__":
    main()
